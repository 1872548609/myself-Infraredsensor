/************************************************************************************************/
/**
 * @file    main.c
 * @brief   槽型开关完整测试程序入口
 ************************************************************************************************/

#include "main.h"

int main(void)
{
    /* 尽早启动看门狗，覆盖后续时钟配置和ADC校准等待。 */
    iwdg_init();

    /* 1. 系统主频配置为48MHz。 */
    system_clock_config();
    std_delay_init();

    /* 2. 初始化NO、NC、LED和PB1/ADC_IN0。 */
    gpio_init();

    /* 3. TIM1以1us为计数单位，周期触发ADC。 */
    tim1_init();

    /* 4. ADC使用16MHz时钟、3周期采样和转换完成中断。 */
    adc_init();

    /* 5. 启动ADC硬件触发采样。 */
    adc_start();

    while(1)
    {
        /* 仅在ADC完成新的处理后喂狗，再等待中断唤醒。 */
        iwdg_service();
        __WFI();
    }
}
